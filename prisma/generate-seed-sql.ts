/**
 * Generates an idempotent SQL data migration from prisma/seed-data/vehicles.json.
 *
 * Why: Netlify Database only allows production writes through deploy-time migrations
 * (CLI credentials for production are read-only), so the sample dataset ships as a
 * migration. Locally, `pnpm db:seed` remains the way to (re)load data.
 *
 * Usage: pnpm db:seed-sql <migration-name>   e.g. pnpm db:seed-sql seed_sample_data
 * Writes prisma/migrations/<timestamp>_<name>/migration.sql.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { FEATURE_CATALOG, isFeatureCode } from "../src/modules/specifications/feature-catalog";
import { seedFileSchema } from "../src/modules/vehicles/schemas";

type Scalar = string | number | boolean | null | undefined | string[];

const lit = (v: Scalar): string => {
  if (v === null || v === undefined) return "NULL";
  if (Array.isArray(v)) return `ARRAY[${v.map(lit).join(", ")}]::TEXT[]`;
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "NULL";
  if (typeof v === "boolean") return v ? "TRUE" : "FALSE";
  return `'${v.replace(/'/g, "''")}'`;
};

const insert = (table: string, row: Record<string, Scalar | { sql: string }>, conflict: string) => {
  const cols = Object.keys(row).map((c) => `"${c}"`).join(", ");
  const vals = Object.values(row)
    .map((v) => (v && typeof v === "object" && "sql" in v ? v.sql : lit(v as Scalar)))
    .join(", ");
  return `INSERT INTO "${table}" (${cols}) VALUES (${vals}) ON CONFLICT (${conflict}) DO NOTHING;`;
};

const ref = (table: string, slug: string) => ({ sql: `(SELECT "id" FROM "${table}" WHERE "slug" = ${lit(slug)})` });

const name = process.argv[2];
if (!name || !/^[a-z0-9_]+$/.test(name)) throw new Error("Pass a migration name like: seed_sample_data");

const data = seedFileSchema.parse(JSON.parse(readFileSync(join(import.meta.dirname, "seed-data", "vehicles.json"), "utf8")));
const out: string[] = [
  "-- Sample dataset (approximate, for demonstration). Generated by prisma/generate-seed-sql.ts — do not edit by hand.",
  "-- Idempotent: existing rows (matched on unique keys) are left untouched.",
];

for (const mk of data.makes) {
  out.push(insert("Make", { id: `make_${mk.slug}`, slug: mk.slug, name: mk.name, country: mk.country }, `"slug"`));
}

for (const m of data.models) {
  out.push(
    insert(
      "Model",
      {
        id: `model_${m.slug}`,
        slug: m.slug,
        name: m.name,
        makeId: ref("Make", m.make),
        bodyType: { sql: `${lit(m.bodyType)}::"BodyType"` },
        modelYear: m.modelYear,
        segment: m.segment,
        summary: m.summary,
        isPopular: m.isPopular,
        imageUrl: m.image?.url,
        imageAuthor: m.image?.author,
        imageLicense: m.image?.license,
        imageLicenseUrl: m.image?.licenseUrl,
        imageSourceUrl: m.image?.sourceUrl,
      },
      `"slug"`,
    ),
  );
  out.push(
    insert(
      "Review",
      { id: `review_${m.slug}`, modelId: ref("Model", m.slug), rating: m.review.rating, verdict: m.review.verdict, pros: m.review.pros, cons: m.review.cons },
      `"modelId"`,
    ),
  );

  for (const v of m.variants) {
    const unknown = v.features.filter((f) => !isFeatureCode(f));
    if (unknown.length) throw new Error(`Variant ${v.slug} has unknown features: ${unknown.join(", ")}`);
    const variantId = ref("Variant", v.slug);

    out.push(
      insert(
        "Variant",
        {
          id: `variant_${v.slug}`,
          slug: v.slug,
          name: v.name,
          modelId: ref("Model", m.slug),
          price: v.price,
          fuelType: { sql: `${lit(v.fuelType)}::"FuelType"` },
          transmission: { sql: `${lit(v.transmission)}::"Transmission"` },
          drivetrain: v.drivetrain,
          seats: v.seats,
        },
        `"slug"`,
      ),
    );
    out.push(insert("Specification", { id: `spec_${v.slug}`, variantId, ...m.defaults.spec, ...v.spec }, `"variantId"`));
    out.push(insert("Performance", { id: `perf_${v.slug}`, variantId, ...v.perf }, `"variantId"`));
    out.push(insert("SafetyRating", { id: `safety_${v.slug}`, variantId, ...m.defaults.safety, ...v.safety }, `"variantId"`));
    out.push(insert("OwnershipCost", { id: `cost_${v.slug}`, variantId, ...m.defaults.cost, ...v.cost }, `"variantId"`));
    for (const code of v.features.filter(isFeatureCode)) {
      const f = FEATURE_CATALOG[code];
      out.push(
        insert(
          "Feature",
          { id: `feature_${v.slug}_${code}`, variantId, name: f.name, category: { sql: `${lit(f.category)}::"FeatureCategory"` } },
          `"variantId", "name"`,
        ),
      );
    }
  }
}

const stamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
const dir = join(import.meta.dirname, "migrations", `${stamp}_${name}`);
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, "migration.sql"), out.join("\n") + "\n");
console.log(`Wrote ${out.length - 2} statements to ${dir}`);
